const VOWELS = /[аеёиоуыэюяaeiouy]/i;
// Часть слова «полная», если в ней есть гласная и она не из одной буквы: нек-рых, а не к-рый или 76-мм.
const full = (part: string) => VOWELS.test(part) && part.length > 1;

// Формулы, ссылки и шапку/подвал страницы не трогаем: там свои правила.
function protect(text: string, fn: (s: string) => string): string {
  const parts = text.split(/(<math[\s\S]*?<\/math>|<noinclude>[\s\S]*?<\/noinclude>|https?:\/\/\S+)/);
  return parts.map((p, i) => (i % 2 ? p : fn(p))).join("");
}

export const fixNd = (s: string) =>
  s.replace(/([\p{L}\d]+)\{\{нд\}\}((?:''|')?)([\p{L}\d]+)/gu, (m, a: string, q: string, b: string) => (full(a) && full(b) ? `${a}-${q}${b}` : m));

export const fixEllipsis = (s: string) => s.replace(/(?<!\.)\.\.\.(?!\.)/g, "…");

export const fixPercent = (s: string) => s.replace(/(\d)(?: |&nbsp;)?%/g, "$1&thinsp;%");

// Неразрывный пробел перед тире, в том числе после запятой (Vladis13, 13 ноября 2026); в таблицах не трогаем.
// Тире без пробела после него (диапазоны, «—CO—NH—») не трогаем.
export const fixDash = (s: string) => s.replace(/([^\s|!=])[ \t]+—(?=[ \t])/g, "$1&nbsp;—");

// Соавторы через «и» — каждый в своём шаблоне, как сделал Egor на т. 22 стр. 244.
export const fixCoauthors = (s: string) =>
  s.replace(/\{\{БСЭ1\/Автор\|([^{}|]+?) и ([^{}|]+)\}\}/g, "{{БСЭ1/Автор|$1}} и {{БСЭ1/Автор|$2}}");


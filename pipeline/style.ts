export const fixLsafe = (s: string) =>
  // В показываемом тексте бывает вложенный шаблон: «Никель {{Ко}} оф Канада».
  s.replace(/\{\{([lL]safe)\|([^{}|]+?)(?:\|((?:[^{}|]|\{\{[^{}]*\}\})*))?\}\}/g, (m, tpl: string, name: string, shown?: string) => {
    const to = (shown !== undefined && LSAFE_RENAMES[`${name}|${shown}`]) || LSAFE_RENAMES[name];
    return to ? `{{${tpl}|${to}|${shown ?? name}}}` : m;
  });

const STEPS: [string, (s: string) => string][] = [
  ["ссылки {{lsafe}} по словнику", fixLsafe],
  ["{{нд}} только при неполном слоге (нек-рых — обычный дефис)", fixNd],
  ["многоточие «…»", fixEllipsis],
  ["тонкий пробел перед %", fixPercent],
  ["неразрывный пробел перед тире", fixDash],
  ["{{razr2}} перед знаком препинания", fixRazr],
  ["соавторы в отдельных {{БСЭ1/Автор}}", fixCoauthors],
];

export function fixStyle(text: string): { text: string; changes: string[] } {
  const changes: string[] = [];
  let out = text;
  for (const [name, fn] of STEPS) {
    const next = protect(out, fn);
    if (next !== out) changes.push(name);
    out = next;
  }
  return { text: out, changes };
}

// Места, которые скрипт не правит сам: их нужно посмотреть по скану.
export function lintStyle(text: string): string[] {
  const warn: string[] = [];
  protect(text, (s) => {
    for (const m of s.matchAll(/(?<![\d\/])\d\/\d+(?![\d\/])/g)) warn.push(`дробь «${m[0]}» набрать символом (½, ⅔) или шаблоном`);
    for (const m of s.matchAll(/(?<![\p{L}\\])(?=\p{L}*\p{Script=Cyrillic})(?=\p{L}*\p{Script=Latin})\p{L}+/gu)) warn.push(`в слове «${m[0]}» смешаны кириллица и латиница`);
    const lines = s.split("\n");
    for (let i = 0; i + 1 < lines.length; i++)
      if (/[\p{Ll},-]$/u.test(lines[i]) && /^\p{Ll}/u.test(lines[i + 1])) warn.push(`перевод строки внутри абзаца: «…${lines[i].slice(-20)}⏎${lines[i + 1].slice(0, 20)}…»`);
    return s;
  });
  return warn;
}

